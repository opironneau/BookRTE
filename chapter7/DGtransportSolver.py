# 6. SOLUTION EVALUATION / POST-PROCESSING
# ============================================================================

def eval_solution(mesh, sp_space, U, mu_pts, z_pts):
    """Evaluate the DG solution at arbitrary points (mu_pts, z_pts) (broadcastable)."""
    mu_pts = np.atleast_1d(np.asarray(mu_pts, dtype=float))
    z_pts = np.atleast_1d(np.asarray(z_pts, dtype=float))
    n_mu, n_z = mesh.n_mu, mesh.n_z
    ndof = sp_space.ndof
    p = sp_space.p
    out = np.zeros(mu_pts.shape)

    a_idx = np.clip(np.searchsorted(mesh.mu_edges, mu_pts, side='right') - 1, 0, n_mu - 1)
    b_idx = np.clip(np.searchsorted(mesh.z_edges, z_pts, side='right') - 1, 0, n_z - 1)

    for i in range(mu_pts.size):
        a, b = a_idx[i], b_idx[i]
        mu0, mu1 = mesh.mu_edges[a], mesh.mu_edges[a + 1]
        z0, z1 = mesh.z_edges[b], mesh.z_edges[b + 1]
        xi = 2.0 * (mu_pts[i] - mu0) / (mu1 - mu0) - 1.0
        eta = 2.0 * (z_pts[i] - z0) / (z1 - z0) - 1.0
        Bxi, _ = basis_1d(p, np.array([xi]))
        Beta, _ = basis_1d(p, np.array([eta]))
        g0 = (b * n_mu + a) * ndof
        val = 0.0
        k = 0
        for ii in range(p + 1):
            for jj in range(p + 1):
                val += U[g0 + k] * Bxi[ii, 0] * Beta[jj, 0]
                k += 1
        out[i] = val
    return out


def build_plot_grid(mesh, sp_space, U, nplot=6):
    """Build a fine structured grid (with cell-local discontinuities preserved)
    of the DG solution for visualisation with pcolormesh/contour."""
    n_mu, n_z = mesh.n_mu, mesh.n_z
    p = sp_space.p
    ndof = sp_space.ndof
    xs = np.linspace(-1.0, 1.0, nplot)
    Bxs, _ = basis_1d(p, xs)                     # (p+1, nplot)

    MU = np.zeros((n_z * nplot, n_mu * nplot))
    ZZ = np.zeros_like(MU)
    UU = np.zeros_like(MU)

    for b in range(n_z):
        z0, z1 = mesh.z_edges[b], mesh.z_edges[b + 1]
        zloc = z0 + 0.5 * (xs + 1.0) * (z1 - z0)
        for a in range(n_mu):
            mu0, mu1 = mesh.mu_edges[a], mesh.mu_edges[a + 1]
            muloc = mu0 + 0.5 * (xs + 1.0) * (mu1 - mu0)
            g0 = (b * n_mu + a) * ndof
            Uloc = U[g0:g0 + ndof].reshape(p + 1, p + 1)   # [i(mu-index), j(z-index)]
            # value at (xi_m, eta_n) = sum_ij Uloc[i,j]*Bxs[i,m]*Bxs[j,n]
            val = np.einsum('ij,im,jn->mn', Uloc, Bxs, Bxs)  # shape (nplot_mu, nplot_z)
            MU[b * nplot:(b + 1) * nplot, a * nplot:(a + 1) * nplot] = muloc[None, :].T * 0 + \
                np.tile(muloc.reshape(-1, 1), (1, nplot))
            ZZ[b * nplot:(b + 1) * nplot, a * nplot:(a + 1) * nplot] = np.tile(zloc.reshape(1, -1), (nplot, 1)).T
            UU[b * nplot:(b + 1) * nplot, a * nplot:(a + 1) * nplot] = val.T
    return MU, ZZ, UU


# ============================================================================
# 7. MAIN DRIVER
# ============================================================================

def solve(p_deg=P_DEG, n_mu=N_MU, n_z=N_Z, Z=Z_DOMAIN, nq=NQ, nfq=NFQ, verbose=True):
    mesh = Mesh(n_mu, n_z, Z)
    space = DGSpace(p_deg, nq, nfq)
    A, F = assemble(mesh, space)
    if verbose:
        print(f"Assembled system: {A.shape[0]} DOFs, {A.nnz} nonzeros "
              f"(p={p_deg}, N_mu={n_mu}, N_z={n_z})")
    U = spla.spsolve(A.tocsc(), F)
    if verbose:
        print(f"Solve done. ||u||_inf = {np.max(np.abs(U)):.6g}")
    return mesh, space, U


